"""Auditable row/year lookup and statement-scoped extraction; no gold inputs."""
from decimal import Decimal, InvalidOperation
import re
from .documents import norm


FIELDS = {
 'revenue':('income',('Total revenue','Total revenues','Revenues','Revenue','Net sales')),
 'operating_income':('income',('Operating income','Operating profit')),
 'net_income':('income',('Net income','Net earnings','Net profit','Profit for the year')),
 'assets':('balance',('Total assets',)),
 'liabilities':('balance',('Total liabilities',)),
 'equity':('balance',('Total stockholders equity','Total shareholders equity','Total shareholders investment','Total equity')),
 'cash':('balance',('Cash and cash equivalents',)),
 'current_assets':('balance',('Total current assets',)),
 'current_liabilities':('balance',('Total current liabilities',)),
 'cfo':('cashflow',('Net cash provided by operating activities','Net cash provided by operations',
                   'Net cash from operating activities','Cash provided by operations',
                   'Net cash from operations','Cash provided by operating activities',
                   'Net cash generated by operating activities')),
 'cash_ppe':('cashflow',('Additions to property and equipment','Purchases of property and equipment',
                       'Purchase of property plant and equipment','Payments for property plant and equipment',
                       'Purchases of property plant and equipment','Expenditures for property and equipment')),
 'da':('cashflow',('Depreciation and amortization','Depreciation and amortisation')),
}
CONTROLS=('current_share_price','customer_count','undisclosed_future_revenue')


def money(text):
    value=text.strip().replace('$','').replace(',','').replace('\u2212','-').strip()
    if value in ('-','—','–','_'):
        return Decimal(0)
    if value.startswith('(') and value.endswith(')'):
        value='-'+value[1:-1]
    if not re.fullmatch(r'-?\d+(?:\.\d+)?',value):
        return None
    try:
        result=Decimal(value)
    except InvalidOperation:
        return None
    return result if result.is_finite() else None


def headers_by_group(rows):
    groups={}
    for row in rows:
        groups.setdefault(row.group,[]).append(row)
    result={}
    for group,items in groups.items():
        heads=[]
        for row in items[:30]:
            years=[t for t in row.tokens if re.fullmatch(r'20\d{2}',t.text.strip())]
            if len({t.text for t in years})>=2:
                # Prefer the earliest complete row; main statements have one.
                heads=years;break
        if heads:result[group]=heads
    return result


def row_label(row, heads, note_left=None):
    first=min(t.left for t in heads)
    if note_left is not None:first=min(first,note_left)
    parts=[]
    for t in row.tokens:
        if t.left>=first:break
        if note_left is not None and re.fullmatch(r'\d+(?:\.\d+)+,?',t.text.strip()):break
        if t.text.strip() in ('$','₹') or money(t.text) is not None:
            continue
        parts.append(t.text)
    label=' '.join(parts)
    label=re.sub(r'\s*\([a-z]\)\s*$','',label,flags=re.I)
    return norm(label),label


def choose_column(row, heads, year):
    columns=[h for h in heads if h.text.strip()==str(year)]
    if len(columns)!=1:
        return None,'ambiguous_or_missing_year'
    selected=columns[0]
    candidates=[]
    for index,token in enumerate(row.tokens):
        text=token.text
        # DOCX accounting parentheses may occupy a separate closing cell.
        if text.startswith('(') and not text.endswith(')') and index+1<len(row.tokens) and row.tokens[index+1].text==')':
            text+=')'
        value=money(text)
        if value is None:continue
        nearest=min(heads,key=lambda h:abs(h.right-token.right))
        if nearest is not selected:continue
        distance=abs(selected.right-token.right)
        limit=2 if row.group.startswith('table:') else 48
        if distance<=limit:
            candidates.append((distance,value,token.text))
    if not candidates:return None,'no_numeric_year_cell'
    best=min(x[0] for x in candidates)
    values=[x for x in candidates if abs(x[0]-best)<1e-9]
    if len({x[1] for x in values})!=1:return None,'conflicting_year_cells'
    return values[0][1],'year_cell'


def extract(meta, rows, field, *, strict, currency='USD'):
    if currency!=meta['currency']:
        return {'value':None,'reason':'currency_mismatch','provenance':[]}
    if field in CONTROLS:
        return {'value':None,'reason':'outside_supported_financial_contract','provenance':[]}
    if field not in FIELDS:
        raise ValueError('Unknown field; do not silently expand the contract')
    if type(strict) is not bool:raise ValueError('Boolean strict mode required')
    kind,aliases=FIELDS[field]
    allowed={norm(label):i for i,label in enumerate(aliases)}
    expected_year=int(meta['period_end'][:4]) if kind=='balance' else meta['fiscal_year']
    heads=headers_by_group(rows)
    note_columns={}
    for row in rows:
        if row.group in heads and any(t.text.strip() in ('Note','Notes') for t in row.tokens) \
                and sum(bool(re.fullmatch(r'20\d{2}',t.text.strip())) for t in row.tokens)>=2:
            note_columns[row.group]=min(t.left for t in row.tokens if t.text.strip() in ('Note','Notes'))
    candidates=[]
    for order,row in enumerate(rows):
        header=heads.get(row.group)
        if not header or (strict and row.section!=kind):continue
        label,source_label=row_label(row,header,note_columns.get(row.group))
        if label not in allowed:continue
        value,reason=choose_column(row,header,expected_year)
        if value is None:continue
        if field=='cash_ppe':value=abs(value)
        value*=Decimal(str(meta['scale_to_millions']))
        provenance={'source':meta['id'],'source_sha256':meta['sha256'],'locator':row.locator,
            'row_label':source_label,'fiscal_year':meta['fiscal_year'],'period_end':meta['period_end'],
            'display_column_year':expected_year,'currency':meta['currency'],'unit':'millions',
            'statement_scope':row.section,'field':field,'normalisation':'absolute cash outflow' if field=='cash_ppe' else 'reported sign',
            'source_value':str(value)}
        candidates.append((allowed[label],order,value,provenance))
    if not candidates:return {'value':None,'reason':'no_supported_row_year_scope','provenance':[]}
    if strict and len({x[2] for x in candidates})!=1:
        return {'value':None,'reason':'conflicting_supported_contexts','provenance':[x[3] for x in candidates]}
    # Aliases are alternative labels for this field, not permission to discard
    # conflicting evidence. Prefer the canonical label only after agreement.
    # If net sales and total revenue differ, this contract cannot infer their
    # economic equivalence and must abstain rather than silently choose one.
    best=min(x[0] for x in candidates)
    candidates=[x for x in candidates if x[0]==best]
    selected=min(candidates,key=lambda x:x[1])
    return {'value':str(selected[2]),'reason':'statement_scoped' if strict else 'literal_lookup',
            'provenance':[x[3] for x in candidates] if strict else [selected[3]]}
